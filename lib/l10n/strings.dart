import 'package:flutter/widgets.dart';

/// Languages shipped by the desktop app: English, Spanish and Japanese.
enum AppLanguage { system, english, spanish, japanese }

AppLanguage languageFromCode(String? code) {
  switch (code) {
    case 'en':
      return AppLanguage.english;
    case 'es':
      return AppLanguage.spanish;
    case 'ja':
      return AppLanguage.japanese;
    default:
      return AppLanguage.system;
  }
}

String languageCode(AppLanguage language) => switch (language) {
  AppLanguage.system => 'system',
  AppLanguage.english => 'en',
  AppLanguage.spanish => 'es',
  AppLanguage.japanese => 'ja',
};

/// Resolves the language actually used for rendering.
AppLanguage resolveLanguage(AppLanguage preference, Locale systemLocale) {
  if (preference != AppLanguage.system) return preference;
  switch (systemLocale.languageCode) {
    case 'es':
      return AppLanguage.spanish;
    case 'ja':
      return AppLanguage.japanese;
    default:
      return AppLanguage.english;
  }
}

