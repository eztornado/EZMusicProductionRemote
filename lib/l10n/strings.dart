/// Exposes the current [L10n] and lets descendants change the preference.
class L10nScope extends InheritedWidget {
  const L10nScope({
    super.key,
    required this.l10n,
    required this.language,
    required this.onLanguageChanged,
    required super.child,
  });

  final L10n l10n;
  final AppLanguage language;
  final ValueChanged<AppLanguage> onLanguageChanged;

  static L10n of(BuildContext context) {
    final scope = context.dependOnInheritedWidgetOfExactType<L10nScope>();
    return scope?.l10n ?? L10n.fallback;
  }

  static L10nScope? maybeOf(BuildContext context) {
    return context.dependOnInheritedWidgetOfExactType<L10nScope>();
  }

  @override
  bool updateShouldNotify(L10nScope oldWidget) =>
      oldWidget.l10n.language != l10n.language;
}

extension L10nContext on BuildContext {
  L10n get l10n => L10nScope.of(this);
  String t(String key, [Map<String, Object?>? vars]) => l10n.t(key, vars);
}
